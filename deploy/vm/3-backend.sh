#!/usr/bin/env bash
# -----------------------------------------------------------------
#  Step 3 of 4 - the backend API as a systemd service.
#
#  Installs npm dependencies, generates the C2PA signing identity
#  (once), writes backend/.env pointing at this VM's Fabric crypto
#  material (Linux paths, peers on localhost), and runs
#  `node src/server.js` under systemd so it restarts on crash/reboot.
#
#  Inputs (prompted for if unset and running in a terminal):
#    PINATA_JWT       required
#    FRONTEND_ORIGIN  optional now - the Vercel URL, set later with
#                     set-frontend-origin.sh once you know it
#    IPFS_GATEWAY     default https://gateway.pinata.cloud/ipfs
#    BROADCASTER_PORTAL_PASSCODE / AUDITOR_PORTAL_PASSCODE
#                     default: random, printed at the end
#
#  An existing backend/.env is kept as-is unless REGENERATE_ENV=1.
# -----------------------------------------------------------------
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/config.sh"

ORGS="$TEST_NETWORK/organizations/peerOrganizations"
[ -d "$ORGS/org3.example.com" ] \
  || die "No Fabric crypto material under $ORGS - run 2-fabric-network.sh first."

cd "$BACKEND_DIR"

step "Installing backend dependencies"
npm ci --omit=dev --no-audit --no-fund
[ -f node_modules/@contentauth/c2pa-node/dist/index.node ] \
  || die "c2pa-node's native binary didn't install - C2PA signing would fail. Check the npm output above."

if [ ! -f certs/c2pa/signing-chain.pem ]; then
  step "Generating the C2PA signing identity (backend/certs/c2pa/)"
  bash scripts/generate-c2pa-cert.sh
else
  step "C2PA signing identity already exists - keeping it"
fi

ENV_FILE="$BACKEND_DIR/.env"
if [ -f "$ENV_FILE" ] && [ "${REGENERATE_ENV:-0}" != "1" ]; then
  step "Keeping existing $ENV_FILE (REGENERATE_ENV=1 to rewrite it)"
else
  step "Writing $ENV_FILE"
  if [ -z "${PINATA_JWT:-}" ]; then
    [ -t 0 ] || die "PINATA_JWT is not set."
    read -rsp "  Pinata JWT (input hidden): " PINATA_JWT; echo
    [ -n "$PINATA_JWT" ] || die "PINATA_JWT is required."
  fi
  if [ -z "${FRONTEND_ORIGIN+x}" ] && [ -t 0 ]; then
    read -rp "  Frontend URL, e.g. https://truststream.vercel.app (Enter to skip for now): " FRONTEND_ORIGIN
  fi
  FRONTEND_ORIGIN="${FRONTEND_ORIGIN:-}"
  IPFS_GATEWAY="${IPFS_GATEWAY:-https://gateway.pinata.cloud/ipfs}"
  BROADCASTER_PORTAL_PASSCODE="${BROADCASTER_PORTAL_PASSCODE:-$(openssl rand -hex 6)}"
  AUDITOR_PORTAL_PASSCODE="${AUDITOR_PORTAL_PASSCODE:-$(openssl rand -hex 6)}"

  for org in 1 2 3; do
    for f in "peers/peer0.org$org.example.com/tls/ca.crt" \
             "users/Admin@org$org.example.com/msp/signcerts/cert.pem" \
             "users/Admin@org$org.example.com/msp/keystore"; do
      [ -e "$ORGS/org$org.example.com/$f" ] || die "Missing $ORGS/org$org.example.com/$f"
    done
  done

  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/vm/3-backend.sh on $(date -u +%Y-%m-%dT%H:%MZ)
PORT=$BACKEND_PORT

PINATA_JWT=$PINATA_JWT
IPFS_GATEWAY=$IPFS_GATEWAY

# Comma-separated allowed frontend origin(s). Empty = CORS wide open.
# Change with deploy/vm/set-frontend-origin.sh
FRONTEND_ORIGIN=$FRONTEND_ORIGIN

FABRIC_ENABLED=true
FABRIC_CHANNEL_NAME=$CHANNEL_NAME
FABRIC_CHAINCODE_NAME=$CC_NAME

# Org1 - NewsAgency (registers media)
FABRIC_MSP_ID=Org1MSP
FABRIC_PEER_ENDPOINT=localhost:7051
FABRIC_PEER_HOST_ALIAS=peer0.org1.example.com
FABRIC_TLS_CERT_PATH=$ORGS/org1.example.com/peers/peer0.org1.example.com/tls/ca.crt
FABRIC_CERT_PATH=$ORGS/org1.example.com/users/Admin@org1.example.com/msp/signcerts/cert.pem
FABRIC_KEY_DIR=$ORGS/org1.example.com/users/Admin@org1.example.com/msp/keystore

# Org2 - Broadcaster (first approval stage)
FABRIC_ORG2_MSP_ID=Org2MSP
FABRIC_ORG2_PEER_ENDPOINT=localhost:9051
FABRIC_ORG2_PEER_HOST_ALIAS=peer0.org2.example.com
FABRIC_ORG2_TLS_CERT_PATH=$ORGS/org2.example.com/peers/peer0.org2.example.com/tls/ca.crt
FABRIC_ORG2_CERT_PATH=$ORGS/org2.example.com/users/Admin@org2.example.com/msp/signcerts/cert.pem
FABRIC_ORG2_KEY_DIR=$ORGS/org2.example.com/users/Admin@org2.example.com/msp/keystore

# Org3 - Auditor (final approval stage)
FABRIC_ORG3_MSP_ID=Org3MSP
FABRIC_ORG3_PEER_ENDPOINT=localhost:11051
FABRIC_ORG3_PEER_HOST_ALIAS=peer0.org3.example.com
FABRIC_ORG3_TLS_CERT_PATH=$ORGS/org3.example.com/peers/peer0.org3.example.com/tls/ca.crt
FABRIC_ORG3_CERT_PATH=$ORGS/org3.example.com/users/Admin@org3.example.com/msp/signcerts/cert.pem
FABRIC_ORG3_KEY_DIR=$ORGS/org3.example.com/users/Admin@org3.example.com/msp/keystore

BROADCASTER_PORTAL_PASSCODE=$BROADCASTER_PORTAL_PASSCODE
AUDITOR_PORTAL_PASSCODE=$AUDITOR_PORTAL_PASSCODE
EOF
  umask 022
fi

step "Installing the $SERVICE_NAME systemd service"
sudo tee "/etc/systemd/system/$SERVICE_NAME.service" >/dev/null <<EOF
[Unit]
Description=TrustStream backend API
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=simple
User=$USER
WorkingDirectory=$BACKEND_DIR
ExecStart=$(command -v node) src/server.js
Restart=always
RestartSec=5
Environment=NODE_ENV=production

[Install]
WantedBy=multi-user.target
EOF
sudo systemctl daemon-reload
sudo systemctl enable "$SERVICE_NAME" >/dev/null
sudo systemctl restart "$SERVICE_NAME"

step "Waiting for the API on localhost:$BACKEND_PORT"
for _ in $(seq 1 30); do
  curl -fsS "http://localhost:$BACKEND_PORT/health" >/dev/null 2>&1 && break
  sleep 1
done
curl -fsS "http://localhost:$BACKEND_PORT/health" >/dev/null 2>&1 \
  || { sudo journalctl -u "$SERVICE_NAME" -n 40 --no-pager; die "Backend didn't come up - log above."; }
sleep 3
sudo journalctl -u "$SERVICE_NAME" -n 8 --no-pager -o cat

step "Done - backend is running"
echo "  Portal passcodes (also in backend/.env):"
grep -E '^(BROADCASTER|AUDITOR)_PORTAL_PASSCODE=' "$ENV_FILE" | sed 's/^/    /'
echo
echo "  Logs:    sudo journalctl -u $SERVICE_NAME -f"
echo "  NEXT:    DOMAIN=<your-subdomain>.duckdns.org $REPO_DIR/deploy/vm/4-https.sh"
